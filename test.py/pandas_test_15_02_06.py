# ffill로 앞 값, bfill로 남은 앞쪽 결측까지 채우기
print("==[ ffill로 앞 값, bfill로 남은 앞쪽 결측까지 채우기 ]==\n")
print(df["전환압력"].isna().sum())  # 68개 NaN 확인

