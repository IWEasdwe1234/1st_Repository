# ~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
ln0 = f"\n{"== " * 15}\n"
ln1 = f"\n{"~" * 30}\n"
ln2 = f"\n{"~ " * 10}\n"

import pandas as pd

CD = "data/16_diecasting.csv"
WD = "data/16_welding.csv"

df = pd.read_csv(CD)

# 실습 1. IQR과 이상치 경계 구하기
print(ln1 + "\n" + ln0 + "\n실습 1. IQR과 이상치 경계 구하기\n" + ln0)

# ~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~

# 사이클타임의 IQR과 1.5배 규칙 하한·상한 계산

# 목표
# IQR과 1.5배 규칙으로 이상치 경계를 구하기

# ~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~

# 단계
# 사이클타임의 25%·75% 값을 구해 IQR(Q3-Q1) 계산
print(ln1 + "\n==[ 사이클타임의 25%·75% 값을 구해 IQR(Q3-Q1) 계산 ]==\n")
Q1 = df["사이클타임"].quantile(0.25)
Q3 = df["사이클타임"].quantile(0.75)
IQR = Q3 - Q1
print(f"25%(Q1) : {Q1}\n75%(Q3) : {Q3}\nIQR(Q3 - Q1) : {IQR}")

# ~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~

# Q1에서 IQR의 1.5배를 빼 하한 계산
print(ln1 + "\n==[ Q1에서 IQR의 1.5배를 빼 하한 계산 ]==\n")
lower = Q1 - IQR * 1.5
print(round(lower, 2))

# ~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~

# Q3에 IQR의 1.5배를 더해 상한 계산
print(ln1 + "\n==[ Q3에 IQR의 1.5배를 더해 상한 계산 ]==\n")
upper = Q1 + IQR * 15
print(round(upper, 2))

# ~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~

# 실습 2. 조건 필터로 이상치 골라내고 개수·비율
print(ln1 + "\n" + ln0 + "\n실습 2. 조건 필터로 이상치 골라내고 개수·비율\n" + ln0)

# 경계 밖 값을 조건으로 골라 개수와 비율 확인

# ~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~

# 단계
# 하한보다 작거나 상한보다 큰 조건을 각각 괄호로 감싸 또는(|)로 연결
print(
    ln1
    + "\n==[ 하한보다 작거나 상한보다 큰 조건을 각각 괄호로 감싸 또는(|)로 연결 ]==\n"
)
mask = (df["사이클타임"] < lower) | (df["사이클타임"] > upper)

# ~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~

# 조건에 맞는 이상치 행만 골라 확인
print(ln1 + "\n==[ 조건에 맞는 이상치 행만 골라 확인 ]==\n")
print(df[mask][["샷", "사이클타임", "상태"]])

# ~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~

# sum으로 개수, mean으로 비율 계산
print(ln1 + "\n==[ sum으로 개수, mean으로 비율 계산 ]==\n")
print(mask.sum(), round(mask.mean() * 100, 1))

# ~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~

# 실습 4. 이상치 제거 후 크기 비교
print(ln1 + "\n" + ln0 + "\n실습 4. 이상치 제거 후 크기 비교\n" + ln0)

# 경계 밖 행을 빼고 남은 크기와 평균 확인

# ~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~

# 단계
# 조건을 뒤집어 정상 범위 행만 남기기
print(ln1 + "\n==[ 조건을 뒤집어 정상 범위 행만 남기기 ]==\n")
정상 = df[~mask]

# ~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~

# 원본과 제거 후의 행 수를 비교
print(ln1 + "\n==[ 원본과 제거 후의 행 수를 비교 ]==\n")
print(len(df), len(정상))

# ~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~

# 제거 후 평균을 구해 변화 확인
print(ln1 + "\n==[ 제거 후 평균을 구해 변화 확인 ]==\n")
print(round(df["사이클타임"].mean(), 2))
print(round(정상["사이클타임"].mean(), 2))

# ~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~

# 실습 5. 경계값 보정 clipping
print(ln1 + "\n" + ln0 + "\n실습 5. 경계값 보정 clipping\n" + ln0)

# 이상치를 버리지 않고 경계값으로 눌러 보정

# ~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~

# 단계
# clip으로 하한보다 작은 값은 하한으로 올리기
print(ln1 + "\n==[ clip으로 하한보다 작은 값은 하한으로 올리기 ]==\n")

# ~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~

# 상한보다 큰 값은 상한으로 내리기
print(ln1 + "\n==[ 상한보다 큰 값은 상한으로 내리기 ]==\n")
보정 = df["사이클타임"].clip(lower=lower, upper=upper)

# ~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~

# 보정 후 최솟값·최댓값·평균 확인
print(ln1 + "\n==[ 보정 후 최솟값·최댓값·평균 확인 ]==\n")
print(round(보정.min(), 2), round(보정.max(), 2))
print(round(보정.mean(), 2))

