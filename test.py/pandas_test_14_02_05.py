# 전체·그룹 통계와 진단표를 한 흐름으로

import pandas as pd

df = pd.read_csv("data/14_hydraulic.csv")
df.info()
print(df.head(4))

# 목표
# 전체 통계부터 그룹 진단표까지 한 흐름으로 종합

# ~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
print(f"\n{"~" * 30}\n")

# 단계
# 온도 열의 전체 평균과 표준편차로 기준선 파악
print("== 온도 열의 전체 평균과 표준편차로 기준선 파악 ==\n")
print("-- 평균 --\n")
print(df["온도"].mean().round(2))  # 45.34

# ~ ~ ~ ~ ~ ~ ~ ~ ~ ~ ~ ~ ~ ~ ~
print(f"\n{"~ " * 15}\n")

print("-- 표준편차 --\n")
print(df["온도"].std().round(2))  # 8.04

# ~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
print(f"\n{"~" * 30}\n")

# 라인별(냉각기상태) 평균(mean)과 중앙값(median)을 함께 구해 치우침 확인
print("== 라인별 평균과 중앙값을 함께 구해 치우침 확인 ==\n")
print(df.groupby("냉각기상태")["온도"].agg(["mean", "median"]).round(2))
#         mean  median
# 냉각기상태
# 고장     54.67   55.45
# 저하     45.46   44.90
# 정상     35.89   35.90 -> 가장 차이가 없다 (튀는 값이 없다!)


# ~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
print(f"\n{"~" * 30}\n")

# 설비 진단표를 온도편차 순으로 정렬해 우선 점검 대상 선정
print("== 설비 진단표를 온도편차 순으로 정렬해 우선 점검 대상 선정 ==\n")
report = (
    df.groupby("밸브상태")
    .agg(평균온도=("온도", "mean"), 온도편차=("온도", "std"), 평균진동=("진동", "mean"))
    .round(2)
)
print(report)
#        평균온도  온도편차  평균진동
# 밸브상태
# 경미    44.86  8.11  0.62
# 심각    46.02  8.40  0.63
# 정상    45.11  7.79  0.61
# 지연    45.86  8.93  0.62

# ~ ~ ~ ~ ~ ~ ~ ~ ~ ~ ~ ~ ~ ~ ~
print(f"\n{"~ " * 15}\n")

# 온도편차가 클수록 점검 대상이란 뜻이니까 내림차순으로 정렬해봅시다
print("-- 온도편차 내림차순으로 정렬 --\n")
print(report.sort_values("온도편차", ascending=(False)))
#        평균온도  온도편차  평균진동
# 밸브상태
# 지연    45.86  8.93  0.62
# 심각    46.02  8.40  0.63
# 경미    44.86  8.11  0.62
# 정상    45.11  7.79  0.61

# ~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
print(f"\n{"~" * 30}\n")
