# 실습 4. zip으로 센서명-값 매핑하기
print("\n실습 4. zip으로 센서명-값 매핑하기\n")

# ======================================================
print("\n======================================================")

# 1. 센서명 리스트와 측정값 리스트를 각각 저장
print("\n1. 센서명 리스트와 측정값 리스트를 각각 저장")

sensor_name = ["온도", "진동", "압력"]
values = [78, 0.5, 95]

# -----------------------------------------------
print("\n-----------------------------------------------")

# 2. zip으로 두 리스트를 짝지어 dict로 변환
print("\n2. zip으로 두 리스트를 짝지어 dict로 변환\n")

sensors = dict(zip(sensor_name, values))
print(sensors)

# -----------------------------------------------
print("\n-----------------------------------------------")

# 3. items로 순회하며 이름-값 쌍 출력
print("\nitems로 순회하며 이름-값 쌍 출력\n")

for sensor_name, value in sensors.items():
    print(sensor_name)
    print(value)
